/* ---------- bar chart (inline, accessible) ----------
   One series. The highlighted bar is the accent colour, the rest are neutral
   context; every bar carries its label and value, so colour is never the only cue. */
function barChart(chart) {
  if (!chart || !chart.items?.length) return "";
  const items = chart.items;
  const dec = chart.decimals ?? 2;
  const unit = chart.unit ?? "";
  const fmt = (v) => `${v < 0 ? "−" : ""}${Math.abs(v).toFixed(dec)}${unit}`;
  const min = Math.min(0, ...items.map((d) => d.value));
  const max = Math.max(0, ...items.map((d) => d.value));
  const span = max - min || 1;
  const zero = ((0 - min) / span) * 100;
  return `
    <figure class="chart">
      <figcaption><span class="chart-title">${esc(chart.title)}</span>${chart.note ? `<span class="chart-note">${esc(chart.note)}</span>` : ""}</figcaption>
      <div class="bars" role="list">
        ${items.map((d) => {
          const x0 = ((Math.min(0, d.value) - min) / span) * 100;
          const w = (Math.abs(d.value) / span) * 100;
          return `
          <div class="bar-row${d.highlight ? " is-highlight" : ""}" role="listitem" tabindex="0" aria-label="${esc(d.label)}: ${fmt(d.value)}">
            <div class="bar-label"><span>${esc(d.label)}</span><span class="bar-value">${fmt(d.value)}</span></div>
            <div class="bar-track">
              ${min < 0 ? `<span class="bar-zero" style="left:${zero}%"></span>` : ""}
              <span class="bar-fill${d.value < 0 ? " neg" : ""}" style="left:${x0}%;width:${Math.max(w, 0.6)}%"></span>
            </div>
          </div>`;
        }).join("")}
      </div>
    </figure>`;
}
